// P[1] = cs[0]
// P[2] = cs[0] + cs[1]
// ...
// P[j+1] = cs[0] + ... + cs[j]
// 所以区间 [l, r] 的和是：


// P[r+1] - P[l]
// 注意这份代码里区间是按 左闭右闭 [l, r] 来理解的。

// 7. 接下来是最关键的双指针部分

