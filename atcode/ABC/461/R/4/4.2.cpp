// 8. r1 和 r2 分别表示什么
// 对于固定左端点 l：

// r1
// 满足下面条件的最小右端点：


// P[r1+1] - P[l] >= K
// 因为它前面的 while 是：


// while(r1<W && P[r1+1]-P[l] < K) ++r1;
// 意思就是：

// 只要当前和还小于 K
// 就把 r1 往右推
// 循环结束后，r1 就是第一个让区间和达到 K 的位置。

// r2
// 满足下面条件的最小右端点：


// P[r2+1] - P[l] > K
// 因为它前面的 while 是：


// while(r2<W && P[r2+1]-P[l] <= K) ++r2;
// 意思就是：

// 只要当前和还小于等于 K
// 就继续往右推
// 循环结束后，r2 就是第一个让区间和严格大于 K 的位置。

// 9. 所以 [r1, r2-1] 这一段都是什么
// 对于固定 l：

// r1 是第一个使和 >= K 的位置
// r2 是第一个使和 > K 的位置
// 那么从 r1 到 r2-1 之间的右端点，满足：


// 区间和 >= K
// 并且
// 区间和 <= K
// 也就是：


// 区间和 = K
// 所以和等于 K 的右端点个数就是：


// r2 - r1
// 这就是这一句的来源：


// if(r1<W&&P[r1+1]-P[l]==K) da+=r2-r1;
// 10. 为什么还要判断 P[r1+1]-P[l]==K
// 因为有可能根本不存在和等于 K 的区间。

// 比如：

// r1 找到的是第一个 > K 的位置
// 或者 r1 == W，已经越界
// 那这时就不能加。

// 所以要先确认：


// r1 没越界，并且 r1 这个位置的和正好等于 K
// 满足时才加：


// r2 - r1
// 11. 为什么 r1、r2 不会回退
// 这就是滑动窗口的关键。

// 因为 cs[j] >= 0，所以前缀和 P 单调不减。

// 对固定 l：

// r1 是第一个使区间和 >= K 的位置
// r2 是第一个使区间和 > K 的位置
// 当 l 变大时，区间和会变小，所以想重新满足条件，右端点只可能右移，不可能左退。

// 所以：


// if(r1<l) r1=l;
// if(r2<l) r2=l;
// 然后两个指针都只会向右走。

// 总共每个指针最多移动 W 次，所以这一层复杂度是 O(W)。

// 12. 这份代码和题解里的“>=K 减 >K”是什么关系
// 题解是概念上这么说：


// count(=K) = count(>=K) - count(>K)
// 这份代码没有显式把两个总数分别算出来，而是对每个左端点 l，直接找出：

// 第一个 >=K 的位置 r1
// 第一个 >K 的位置 r2
// 于是：


// 对这个 l 来说，和等于 K 的右端点个数 = r2 - r1
// 这其实就是“>=K 减 >K”在每个 l 上的局部实现。

// 13. 你可以这样理解这两个指针
// 固定一个左端点 l 时，右端点 r 的区间和会随着 r 增大而单调不减。

// 所以右端点们会分成三段：

// 第一段：和小于 K

// r < r1
// 第二段：和等于 K

// r1 <= r < r2
// 第三段：和大于 K

// r >= r2
// 于是和等于 K 的个数就是中间这一段长度：


// r2 - r1
// 这个视角特别重要。

// 14. 为什么这里会有一整段“等于 K”
// 因为 cs[j] 里可能有 0。

// 如果中间加了几列都是 0，那么区间和不变，所以可能出现：


// 同一个左端点 l
// 有多个连续的右端点 r
// 都满足和 = K
// 例如：


// cs = [1, 0, 0, 2]
// K = 1
// 固定 l=0 时：

// r=0，和 = 1
// r=1，和 = 1
// r=2，和 = 1
// 所以答案不是只加 1，而是加一段长度。

// 这就是为什么代码用：


// da += r2 - r1;
// 而不是只 ++da。

// 15. 这份代码的复杂度
// 外层
// 枚举上边界、下边界：


// O(H^2)
// 每次固定上下边界
// 更新列和 cs：O(W)
// 求前缀和 P：O(W)
// 双指针统计：O(W)
// 所以每次是：


// O(W)
// 总复杂度：


// O(H^2 * W)
// 16. 一句话总结这份代码的思路
// 这份代码的核心是：


// 固定上下边界后，把矩形问题压成一维列和数组 cs；
// 再对 cs 做前缀和 P；
// 对于每个左端点 l，用两个单调右移的指针 r1、r2 分别找到
