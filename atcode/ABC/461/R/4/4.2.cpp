#include<bits/stdc++.h>
using namespace std;
int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    int H,W,K;
    cin>>H>>W>>K;
    vector<string> gd(H);
    for(int i=0;i<H;++i)cin>>gd[i];
    if(H>W)
    {
        vector<string> ts(W,string(H,'0'));
        for(int i=0;i<H;++i) for(int j=0;j<W;++j) ts[j][i]=gd[i][j];
        swap(H,W);
        gd=move(ts);
    }
    vector<vector<int>> A(H,vector<int>(W));
    for(int i=0;i<H;++i) for(int j=0;j<W;++j) A[i][j]=(gd[i][j]=='1');
    vector<int> cs(W,0);
    vector<int> P(W+1,0);
    long long da=0;
    for(int cc=0;cc<H;++cc)
    {
        fill(cs.begin(),cs.end(),0);
        for(int bt=cc;bt<H;++bt)
        {
            for(int j=0;j<W;++j) cs[j]+=A[bt][j];
            int sum=0;
            for(int j=0;j<W;++j)
            {
                sum+=cs[j];
                P[j+1]=sum;
            }
            int r1=0,r2=0;
            for(int l=0;l<W;++l)
            {
                if(r1<l) r1=l;
                if(r2<l) r2=l;
                while(r1<W&&P[r1+1]-P[l]<K) ++r1;
                while(r2<W&&P[r2+1]-P[l]<=K) ++r2;
                if(r1<W&&P[r1+1]-P[l]==K) da+=r2-r1;
            }
        }
    }
    cout<<da<<'\n';
    return 0;
}

